// CSS property names and their internal identifiers.
//
// Guchho's CSS pipeline works with compact numeric identifiers instead of
// comparing raw property-name strings. Every property Guchho is able to emit
// is enumerated here, which includes standard CSS properties, SVG
// presentation attributes that can appear inside stylesheets (fill, stroke,
// paint-order, ...), legacy aliases kept verbatim for compatibility
// (kDWordWrap, kDCssFloat), the CSS Modules "composes" pseudo-property, and
// a small set of Guchho-internal helper properties (kDCssText).
//
// The lowercase, hyphenated spelling used in real stylesheets
// (e.g. "border-bottom-left-radius") is the canonical form referenced
// throughout the printer and exposed via the declarations lookup map.

