#!/usr/bin/env bash

set -euo pipefail

# ========================================
# publish-winget.sh
# Submit the generated Guchho manifests to
# the Windows Package Manager community
# repository (microsoft/winget-pkgs).
#
# WinGet has no package feed to push to:
# publishing means opening a pull request
# against microsoft/winget-pkgs. This script
# uses wingetcreate's `submit` command,
# which forks the repository, copies the
# manifests into the right partition and
# opens the PR for you.
#
# Usage:
#   bash scripts/publish-winget.sh              # submit
#   bash scripts/publish-winget.sh --dry-run    # validate + print the command
#
# Requirements:
#   - manifests generated by scripts/build-winget.sh
#   - wingetcreate (winget install Microsoft.WingetCreate)
#   - a GitHub token via WINGET_CREATE_GITHUB_TOKEN or --token
#
# Prefer WINGET_CREATE_GITHUB_TOKEN, which wingetcreate reads itself. An
# explicit --token value is never printed: the dry run shows it as ***.
# ========================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

PACKAGE_ID="Guchho.Guchho"
DEFAULT_OUTDIR="${ROOT_DIR}/dist/winget"

# ========================================
# Options
# ========================================

VERSION=""
OUTDIR="${DEFAULT_OUTDIR}"
TOKEN="${WINGET_CREATE_GITHUB_TOKEN:-}"
TOKEN_FROM_FLAG=0
PR_TITLE=""
DRY_RUN=0
VALIDATE=1

# ========================================
# Helpers
# ========================================

# Wingetcreate on Windows cannot resolve MSYS POSIX paths (/c/...).
# cygpath -m converts them to native paths (C:/Users/...).
to_winpath() {
    local p="$1"
    if command -v cygpath >/dev/null 2>&1; then
        cygpath -m "${p}"
    else
        echo "${p}"
    fi
}

ROOT_DIR_WIN="$(to_winpath "${ROOT_DIR}")"

log() {
    echo "[Guchho] $*"
}

warn() {
    echo "[WARN] $*" >&2
}

error() {
    echo
    echo "[ERROR] $*" >&2
    echo
    exit 1
}

usage() {
    cat <<'EOF'
Usage: bash scripts/publish-winget.sh [options]

Submit the manifests produced by scripts/build-winget.sh to
microsoft/winget-pkgs with wingetcreate. A GitHub token is required;
prefer the environment variable so it does not appear in shell history:

  export WINGET_CREATE_GITHUB_TOKEN=<token>
  bash scripts/publish-winget.sh

Options:
  --version <x.y.z>   Version to publish (default: package/npm/guchho/package.json)
  --output <dir>      Directory holding manifests/ (default: dist/winget)
  --token <token>     GitHub token (default: WINGET_CREATE_GITHUB_TOKEN)
  --pr-title <title>  Pull request title (default: wingetcreate's own title)
  --no-validate       Skip `winget validate` even when winget is installed
  --dry-run           Validate and print the submit command; upload nothing
  -h, --help          Show this help and exit
EOF
}

# ========================================
# Argument parsing
# ========================================

while [[ $# -gt 0 ]]; do
    case "$1" in
        --version)
            [[ $# -ge 2 ]] || error "--version needs a value"
            VERSION="$2"
            shift 2
            ;;
        --version=*)
            VERSION="${1#*=}"
            shift
            ;;
        --output)
            [[ $# -ge 2 ]] || error "--output needs a value"
            OUTDIR="$2"
            shift 2
            ;;
        --output=*)
            OUTDIR="${1#*=}"
            shift
            ;;
        --token)
            [[ $# -ge 2 ]] || error "--token needs a value"
            TOKEN="$2"
            TOKEN_FROM_FLAG=1
            shift 2
            ;;
        --token=*)
            TOKEN="${1#*=}"
            TOKEN_FROM_FLAG=1
            shift
            ;;
        --pr-title)
            [[ $# -ge 2 ]] || error "--pr-title needs a value"
            PR_TITLE="$2"
            shift 2
            ;;
        --pr-title=*)
            PR_TITLE="${1#*=}"
            shift
            ;;
        --no-validate)
            VALIDATE=0
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "[ERROR] Unknown option: $1" >&2
            echo >&2
            usage >&2
            exit 2
            ;;
    esac
done

# ========================================
# Read version
# ========================================

if ! command -v node >/dev/null 2>&1; then
    error "Node.js was not found. Install it first: https://nodejs.org"
fi

if [[ -z "${VERSION}" ]]; then
    VERSION=$(node -p "require('${ROOT_DIR_WIN}/package/npm/guchho/package.json').version")
fi

if [[ ! "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-.][0-9A-Za-z.-]+)?$ ]]; then
    error "Version is not a version number: ${VERSION}"
fi

echo "========================================"
echo " PUBLISH GUCHHO TO WINGET"
echo "========================================"
echo

if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "** DRY RUN MODE -- no pull request will be opened **"
    echo
fi

echo "Package : ${PACKAGE_ID}"
echo "Version : ${VERSION}"
echo

# ========================================
# Validate the generated manifests
# ========================================

echo "========================================"
echo "[1/3] Checking manifests"
echo "========================================"
echo

VERSION_DIR="${OUTDIR}/manifests/g/Guchho/Guchho/${VERSION}"

if [[ ! -d "${VERSION_DIR}" ]]; then
    error "Manifests not found at ${VERSION_DIR}
        Generate them first:
          bash scripts/build-winget.sh"
fi

REQUIRED_FILES=(
    "${VERSION_DIR}/${PACKAGE_ID}.yaml"
    "${VERSION_DIR}/${PACKAGE_ID}.installer.yaml"
)

for required in "${REQUIRED_FILES[@]}"; do
    if [[ ! -f "${required}" ]]; then
        error "Missing manifest: ${required}
        Re-run: bash scripts/build-winget.sh"
    fi
done

LOCALE_COUNT=0
for locale_file in "${VERSION_DIR}/${PACKAGE_ID}".locale.*.yaml; do
    [[ -f "${locale_file}" ]] || continue
    LOCALE_COUNT=$(( LOCALE_COUNT + 1 ))
done

if [[ "${LOCALE_COUNT}" -eq 0 ]]; then
    error "No default-locale manifest found in ${VERSION_DIR}
        Re-run: bash scripts/build-winget.sh"
fi

log "Found ${#REQUIRED_FILES[@]} manifest(s) + ${LOCALE_COUNT} locale file(s):"
echo "  ${VERSION_DIR}"
echo

VERSION_DIR_WIN="$(to_winpath "${VERSION_DIR}")"

if [[ "${VALIDATE}" -eq 1 ]] && command -v winget >/dev/null 2>&1; then
    log "Running winget validate ..."
    if ! winget validate --manifest "${VERSION_DIR_WIN}"; then
        error "winget validate rejected ${VERSION_DIR}
        Regenerate the manifests or update the Windows Package Manager."
    fi
    echo
elif [[ "${VALIDATE}" -eq 1 ]]; then
    warn "winget was not found; skipping local validation."
    echo
else
    log "Validation skipped (--no-validate)."
    echo
fi

# ========================================
# Check wingetcreate
# ========================================

echo "========================================"
echo "[2/3] Checking wingetcreate"
echo "========================================"
echo

if ! command -v wingetcreate >/dev/null 2>&1; then
    if [[ "${DRY_RUN}" -eq 1 ]]; then
        warn "wingetcreate was not found; the dry run will still show the command."
        echo "  Install it with: winget install Microsoft.WingetCreate"
        echo
    else
        error "wingetcreate was not found. Install it first:
          winget install Microsoft.WingetCreate"
    fi
else
    log "wingetcreate: $(command -v wingetcreate)"
    echo
fi

# ========================================
# Build and run the submit command
# ========================================

echo "========================================"
echo "[3/3] Submitting to microsoft/winget-pkgs"
echo "========================================"
echo

SUBMIT_CMD=(wingetcreate submit)

if [[ -n "${PR_TITLE}" ]]; then
    SUBMIT_CMD+=(--prtitle "${PR_TITLE}")
fi

# A token supplied through the environment is read by wingetcreate itself,
# which is the recommended path: --token may end up in logs. Only pass the
# flag when the user asked for it explicitly.
if [[ "${TOKEN_FROM_FLAG}" -eq 1 && -n "${TOKEN}" ]]; then
    SUBMIT_CMD+=(--token "${TOKEN}")
fi

SUBMIT_CMD+=("${VERSION_DIR_WIN}")

# Print the command with an explicit token redacted. The real value only
# travels in SUBMIT_CMD, which is executed directly rather than through the
# shell.
print_command() {
    local arg first=1
    for arg in "${SUBMIT_CMD[@]}"; do
        [[ "${first}" -eq 1 ]] || printf ' '
        first=0

        if [[ "${TOKEN_FROM_FLAG}" -eq 1 && -n "${TOKEN}" && "${arg}" == "${TOKEN}" ]]; then
            printf '***'
        elif [[ "${arg}" == *' '* ]]; then
            printf '"%s"' "${arg}"
        else
            printf '%s' "${arg}"
        fi
    done
    printf '\n'
}

printf '> '
print_command
echo

if [[ "${TOKEN_FROM_FLAG}" -eq 1 && -n "${TOKEN}" ]]; then
    log "Token: provided with --token (redacted)"
elif [[ -n "${TOKEN}" ]]; then
    log "Token: provided via WINGET_CREATE_GITHUB_TOKEN"
else
    warn "No token provided. wingetcreate will use its cached token, if one exists."
    warn "Set WINGET_CREATE_GITHUB_TOKEN or run 'wingetcreate token -s' first."
fi
echo

if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "(dry run) No pull request was opened."
    echo
    exit 0
fi

"${SUBMIT_CMD[@]}"
echo

# ========================================
# Summary
# ========================================

echo "========================================"
echo " SUBMIT COMPLETE"
echo "========================================"
echo
echo "Submitted: ${PACKAGE_ID} ${VERSION}"
echo
echo "wingetcreate prints the pull request URL above. Once it is merged,"
echo "users can install with:"
echo "  winget install ${PACKAGE_ID}"
echo
