    std::optional<std::string> MaybeCorrectDeclarationTypo(std::string_view text) {
        if (text.starts_with("--")) {
            return std::nullopt;
        }

        static helpers::TypoDetector* detector = nullptr;
        static std::mutex mtx;

        std::lock_guard<std::mutex> lock(mtx);
        if (detector == nullptr) {
            std::vector<std::string> valid;
            valid.reserve(KnownDeclarations.size());
            for (auto& entry : KnownDeclarations) {
                valid.push_back(std::string(entry.first));
            }
            detector = new helpers::TypoDetector(valid);
        }

        return detector->MaybeCorrectTypo(text);
    }
