    JSFeature UnsupportedJSFeatures(const std::unordered_map<Engine, Semver>& constraints) {
        JSFeature unsupported = static_cast<JSFeature>(0);
        for (const auto& [feature, engines] : kJsTable) {
            if (feature == JSFeature::kInlineScript) {
                continue; // This is purely user-specified
            }
            for (const auto& [engine, version] : constraints) {
                auto it = engines.find(engine);
                if (it == engines.end() || !IsVersionSupported(it->second, version)) {
                    unsupported |= feature;
                }
            }
        }
        return unsupported;
    }
