    // Maps the exact, lowercase, hyphenated spelling of a property (as it
    // appears in a stylesheet) to its Declarations identifier. Keys are
    // compared byte-for-byte, so lookups are strictly case-sensitive.
    //
    // Example:
    //   KnownDeclarations.at("border-bottom-left-radius") -> kDBorderBottomLeftRadius
    //   KnownDeclarations.at("max-width")                 -> kDMaxWidth
    //   KnownDeclarations.contains("color")               -> true
    //
    // The table is immutable once static initialization completes and is
    // shared read-only across all threads. Besides direct property lookups,
    // it also feeds the set of valid names used by MaybeCorrectDeclarationTypo.
    extern const std::unordered_map<std::string_view, Declarations> KnownDeclarations;

    // Attempts to recover the intended property name when "text" is
    // misspelled by comparing it against every known declaration and
    // returning the closest candidate. A non-null result is always one of
    // the canonical spellings held in KnownDeclarations.
    //
    // Example:
    //   MaybeCorrectDeclarationTypo("boder-radius")   -> optional("border-radius")
    //   MaybeCorrectDeclarationTypo("animation-name") -> nullopt (already correct)
    //   MaybeCorrectDeclarationTypo("--my-scale")     -> nullopt (custom property)
    //
    // Behavior and edge cases:
    //   - Custom properties (any name starting with "--", e.g. "--my-scale")
    //     always yield nullopt: user-defined names must never be rewritten.
    //   - The spelling detector is built lazily on first use and guarded by
    //     a mutex, so the first call is slightly slower but every subsequent
    //     call reuses the precomputed table.
    //   - The call also returns nullopt when the text is already valid or is
    //     too far from any known property; callers can therefore distinguish
    //     "no correction needed" from "nothing to fix".
    std::optional<std::string> MaybeCorrectDeclarationTypo(std::string_view text);
