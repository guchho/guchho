#!/usr/bin/env bash

set -euo pipefail

# ========================================
# publish_brew.sh
# Publish the generated formula to a
# Homebrew tap.
#
# Homebrew has no registry to push to: a
# formula is published by committing it to a
# tap repository. This script clones the tap,
# installs Formula/guchho.rb, and pushes the
# change on the tap's default branch.
#
# For homebrew-core, the same formula is
# submitted by pull request with
# `brew bump-formula-pr`, which this script
# does not attempt against a tap.
#
# Usage:
#   bash scripts/publish_brew.sh                 # publish
#   bash scripts/publish_brew.sh --dry-run       # show what would change
#
# Requirements:
#   - formula generated by scripts/build_brew.sh
#   - gh (authenticated: gh auth login)
#   - git
#
# The tap defaults to guchho/homebrew-tap. Override it with --tap or
# GUCHHO_HOMEBREW_TAP. A missing tap is only created with --create-tap.
# ========================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

FORMULA_NAME="guchho"
DEFAULT_TAP="guchho/homebrew-tap"
DEFAULT_FORMULA="${ROOT_DIR}/dist/homebrew/Formula/${FORMULA_NAME}.rb"

# ========================================
# Options
# ========================================

VERSION=""
TAP="${GUCHHO_HOMEBREW_TAP:-${DEFAULT_TAP}}"
FORMULA="${DEFAULT_FORMULA}"
BRANCH=""
MESSAGE=""
CREATE_TAP=0
DRY_RUN=0
VALIDATE=1

WORK=""

# ========================================
# Helpers
# ========================================

# Node on Windows cannot resolve MSYS POSIX paths (/c/...).
# cygpath -m converts them to native paths (C:/Users/...).
to_winpath() {
    local p="$1"
    if command -v cygpath >/dev/null 2>&1; then
        cygpath -m "${p}"
    else
        echo "${p}"
    fi
}

ROOT_DIR_WIN="$(to_winpath "${ROOT_DIR}")"

log() {
    echo "[Guchho] $*"
}

warn() {
    echo "[WARN] $*" >&2
}

error() {
    echo
    echo "[ERROR] $*" >&2
    echo
    exit 1
}

cleanup() {
    if [[ -n "${WORK}" && -d "${WORK}" ]]; then
        rm -rf "${WORK}"
    fi
}

trap cleanup EXIT

usage() {
    cat <<'EOF'
Usage: bash scripts/publish_brew.sh [options]

Commit the formula produced by scripts/build_brew.sh to a Homebrew tap.

Options:
  --version <x.y.z>   Version to publish (default: package/npm/guchho/package.json)
  --tap <owner/repo>  Tap repository (default: guchho/homebrew-tap)
  --formula <path>    Formula file (default: dist/homebrew/Formula/guchho.rb)
  --branch <name>     Branch to push (default: the tap's default branch)
  --message <msg>     Commit message (default: "guchho <version>")
  --create-tap        Create the tap repository when it does not exist
  --no-validate       Skip the ruby -c syntax check
  --dry-run           Clone and show the change; do not commit or push
  -h, --help          Show this help and exit

The tap can also be set with the GUCHHO_HOMEBREW_TAP environment variable.
EOF
}

# ========================================
# Argument parsing
# ========================================

while [[ $# -gt 0 ]]; do
    case "$1" in
        --version)
            [[ $# -ge 2 ]] || error "--version needs a value"
            VERSION="$2"
            shift 2
            ;;
        --version=*)
            VERSION="${1#*=}"
            shift
            ;;
        --tap)
            [[ $# -ge 2 ]] || error "--tap needs a value"
            TAP="$2"
            shift 2
            ;;
        --tap=*)
            TAP="${1#*=}"
            shift
            ;;
        --formula)
            [[ $# -ge 2 ]] || error "--formula needs a value"
            FORMULA="$2"
            shift 2
            ;;
        --formula=*)
            FORMULA="${1#*=}"
            shift
            ;;
        --branch)
            [[ $# -ge 2 ]] || error "--branch needs a value"
            BRANCH="$2"
            shift 2
            ;;
        --branch=*)
            BRANCH="${1#*=}"
            shift
            ;;
        --message)
            [[ $# -ge 2 ]] || error "--message needs a value"
            MESSAGE="$2"
            shift 2
            ;;
        --message=*)
            MESSAGE="${1#*=}"
            shift
            ;;
        --create-tap)
            CREATE_TAP=1
            shift
            ;;
        --no-validate)
            VALIDATE=0
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "[ERROR] Unknown option: $1" >&2
            echo >&2
            usage >&2
            exit 2
            ;;
    esac
done

# ========================================
# Read version
# ========================================

if ! command -v node >/dev/null 2>&1; then
    error "Node.js was not found. Install it first: https://nodejs.org"
fi

if [[ -z "${VERSION}" ]]; then
    VERSION=$(node -p "require('${ROOT_DIR_WIN}/package/npm/guchho/package.json').version")
fi

if [[ ! "${VERSION}" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-.][0-9A-Za-z.-]+)?$ ]]; then
    error "Version is not a version number: ${VERSION}"
fi

if [[ -z "${MESSAGE}" ]]; then
    MESSAGE="guchho ${VERSION}"
fi

if [[ ! "${TAP}" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
    error "--tap is not an owner/repository pair: ${TAP}"
fi

echo "========================================"
echo " PUBLISH GUCHHO TO A HOMEBREW TAP"
echo "========================================"
echo

if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "** DRY RUN MODE -- nothing will be committed or pushed **"
    echo
fi

echo "Formula : ${FORMULA}"
echo "Version : ${VERSION}"
echo "Tap     : ${TAP}"
echo

# ========================================
# Validate the formula
# ========================================

echo "========================================"
echo "[1/4] Checking the formula"
echo "========================================"
echo

[[ -f "${FORMULA}" ]] || error "Formula not found at ${FORMULA}
        Generate it first:
          bash scripts/build_brew.sh"

FORMULA_WIN="$(to_winpath "${FORMULA}")"

if [[ "${VALIDATE}" -eq 1 ]] && command -v ruby >/dev/null 2>&1; then
    log "Running ruby -c ..."
    if ! ruby -c "${FORMULA_WIN}"; then
        error "ruby -c rejected ${FORMULA}"
    fi
    echo
elif [[ "${VALIDATE}" -eq 1 ]]; then
    warn "ruby was not found; skipping the syntax check."
    echo
else
    log "Validation skipped (--no-validate)."
    echo
fi

# ========================================
# Check the tap
# ========================================

echo "========================================"
echo "[2/4] Checking the tap"
echo "========================================"
echo

if ! command -v gh >/dev/null 2>&1; then
    error "gh was not found. Install the GitHub CLI: https://cli.github.com"
fi

if ! command -v git >/dev/null 2>&1; then
    error "git was not found. Install it first: https://git-scm.com"
fi

if ! gh auth status >/dev/null 2>&1; then
    error "gh is not authenticated. Run: gh auth login"
fi

TAP_EXISTS=1
TAP_ERROR_FILE="$(mktemp)"

if ! TAP_JSON="$(gh repo view "${TAP}" --json defaultBranchRef 2>"${TAP_ERROR_FILE}")"; then
    if grep -qiE "not found|could not resolve" "${TAP_ERROR_FILE}"; then
        TAP_EXISTS=0
    else
        error "gh could not query ${TAP}:
$(cat "${TAP_ERROR_FILE}")"
    fi
fi
rm -f "${TAP_ERROR_FILE}"

if [[ "${TAP_EXISTS}" -eq 0 ]]; then
    if [[ "${CREATE_TAP}" -eq 1 ]]; then
        if [[ "${DRY_RUN}" -eq 1 ]]; then
            log "Would create tap: ${TAP}"
        else
            log "Creating tap: ${TAP}"
            gh repo create "${TAP}" --public --add-readme \
                --description "Homebrew tap for Guchho" >/dev/null
            TAP_EXISTS=1
        fi
    else
        error "Tap repository not found: ${TAP}
        Create it with:
          gh repo create ${TAP} --public --add-readme
        or re-run with --create-tap."
    fi
fi

if [[ -z "${BRANCH}" ]]; then
    BRANCH=$(gh repo view "${TAP}" --json defaultBranchRef \
        -q '.defaultBranchRef.name' 2>/dev/null || true)
    if [[ -z "${BRANCH}" || "${BRANCH}" == "null" ]]; then
        BRANCH="main"
    fi
fi

log "Tap exists : $([[ "${TAP_EXISTS}" -eq 1 ]] && echo yes || echo "no (will be created)")"
log "Branch     : ${BRANCH}"
log "Message    : ${MESSAGE}"
echo

# ========================================
# Clone and compare
# ========================================

echo "========================================"
echo "[3/4] Applying the formula"
echo "========================================"
echo

if [[ "${DRY_RUN}" -eq 1 && "${TAP_EXISTS}" -eq 0 ]]; then
    echo "Would clone ${TAP}, write Formula/${FORMULA_NAME}.rb, commit and push."
    echo
    echo "Run again without --dry-run to publish."
    echo
    exit 0
fi

WORK="$(mktemp -d)"
TAP_DIR="${WORK}/tap"

log "Cloning ${TAP} ..."
if ! gh repo clone "${TAP}" "${TAP_DIR}" -- --quiet; then
    error "Could not clone ${TAP}"
fi

if ! git -C "${TAP_DIR}" rev-parse --verify "${BRANCH}" >/dev/null 2>&1; then
    error "Branch not found in ${TAP}: ${BRANCH}"
fi
git -C "${TAP_DIR}" checkout --quiet "${BRANCH}"

mkdir -p "${TAP_DIR}/Formula"
cp "${FORMULA}" "${TAP_DIR}/Formula/${FORMULA_NAME}.rb"

# Stage before comparing. Comparing the working tree instead would report a
# change on a clone whose core.autocrlf rewrote the checked-out line endings,
# even when the file commits byte-identically to what is already there.
git -C "${TAP_DIR}" add "Formula/${FORMULA_NAME}.rb"

if git -C "${TAP_DIR}" diff --cached --quiet; then
    log "Formula is already up to date in ${TAP} (${BRANCH})."
    echo
    exit 0
fi

log "Change:"
git -C "${TAP_DIR}" --no-pager diff --cached
echo

if [[ "${DRY_RUN}" -eq 1 ]]; then
    echo "Would commit and push to ${TAP} (${BRANCH})."
    echo
    echo "Run again without --dry-run to publish."
    echo
    exit 0
fi

# ========================================
# Commit and push
# ========================================

echo "========================================"
echo "[4/4] Pushing to ${TAP}"
echo "========================================"
echo

git -C "${TAP_DIR}" commit --quiet -m "${MESSAGE}"

log "Pushing ${BRANCH} ..."
git -C "${TAP_DIR}" push origin "${BRANCH}"

echo

# ========================================
# Summary
# ========================================

TAP_OWNER="${TAP%%/*}"
TAP_REPO_NAME="${TAP#*/}"
TAP_SHORT="${TAP_REPO_NAME#homebrew-}"

echo "========================================"
echo " PUBLISH COMPLETE"
echo "========================================"
echo
echo "Published: ${FORMULA_NAME} ${VERSION} -> ${TAP}"
echo
echo "Users can now install with:"
echo "  brew install ${TAP_OWNER}/${TAP_SHORT}/${FORMULA_NAME}"
echo "  brew update && brew upgrade ${FORMULA_NAME}"
echo
